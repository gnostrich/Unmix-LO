"""
experiments/color_symmetry.py — the color-symmetry DIAGNOSIS + FIX cycle. Direct executable of
ebr/PREREG_color_symmetry.md (committed at HEAD 57b7afd BEFORE this file was written or run); the two legs,
their instruments, the gate rule between them, and every numeric bar are taken from that file verbatim and
NOT re-tuned after seeing numbers.

AUDIT CLASSIFICATION: experimental CONTROL + SUBSTRATE (data-distribution) change. THE ROUTER IS UNTOUCHED —
routing remains the existing untied `energy.functional.equilibrate` exactly as in overlap_routing.py (whose
machinery this file imports and reuses verbatim: member-channel roster, encoding, routing, readout, scoring).
The only new code is (a) two measurement INSTRUMENTS over existing geometries (D-leg: attribute-structure
ratio rho + exchangeability swap test) and (b) a one-parameter change to the WORLD SAMPLER (color_physics
speed multipliers = world v2, F-leg). No new mechanism, no QC, no shim, no force-pass.

HYPOTHESIS (prereg, stated before any number): untied relational routing transfers exactly those attributes
that BREAK the exchangeability of the probe geometry. In world v1 color is assigned independently of
everything, so the color sub-populations are exchangeable — a global color permutation is a near-symmetry of
each member's D, i.e. color lies INSIDE the GW free-lunch orbit and cannot route. Shape/motion route because
they deform geometry asymmetrically.

GATE (prereg, to the letter): the D-leg runs first and CONFIRMS iff
    (i)  under-encoding:  rho_color < rho_shape on the pixel-vision members (vit/clip/siglip renders), AND/OR
    (ii) exchangeability: rel-diff(color swap) <= rel-diff(shape swap)/2 on a MAJORITY of member-channels.
The D-leg FAILS (diagnosis wrong) if color is both well-encoded AND non-exchangeable — then the F-leg is
NOT run; stop and report straight.

F-LEG (only if gated open): world v2 = identical sampler except per-color speed multipliers on the initial
velocity draw {red 2.0, blue 0.5, green 1.4, yellow 0.9} (prereg: ~4x spread between extremes, the minimal
one-parameter symmetry-breaking; nothing else changes; renders/captions/dynamics regenerated by the SAME
code). Re-run the untied condition-B FORWARD task of overlap_routing.py verbatim on the fresh v2 substrate.
Registered bars: B(v2) color >= 0.50 AND B(v2)color - 0.351 >= 0.15; shape >= 0.476-0.10 and
motion >= 0.465-0.10 (no collateral collapse); gauge |dF| < 1e-6 under scramble.

HONEST CONFOUND (prereg, must appear in the final report): in v2 a text member can reach color VIA motion
words alone (red <-> fast). v2 color recovery therefore proves that SYMMETRY-BREAKING COVARIANCE routes —
NOT that pixel-color routes. Stated in the final print.

DEFENDED CONSTANTS: COLOR_PHYSICS multipliers from PREREG_color_symmetry.md; the color/shape permutations
from the same prereg; V1_B_FWD = the recorded condition-B forward accuracies of the committed
overlap-routing run (316f648), used as the registered baseline; N=256, K=24, M=14, seeds {0,1,2}, probe
seeds 0..255, held-out 1000..1023, chance floors, scramble seed — ALL inherited from overlap_routing.py
(itself defended against PREREG_overlap_routing.md). Nothing tuned here.

DISCIPLINE: whichever branch lands is reported straight — empirically-pinned / covariance-insufficient /
diagnosis-wrong. No dressing.

Run: python -m ebr.experiments.color_symmetry
(D-leg reuses overlap_routing's v1 cache; only the two swapped probe sets and the v2 substrate/queries need
fresh encoding, cached under ebr/experiments/_overlap_cache/ with tags colorswap/shapeswap/v2/v2q.)
"""
import os
import numpy as np

from ..demo import world as W
from ..demo.ports import load_ports
from ..geometry.clouds import cloud_to_Dw
from .overlap_routing import (N, K, M, SEEDS, SUBSTRATE_SEEDS, QUERY_SEEDS, CHANCE, CACHE,
                              MEMBERS, MSPEC, _encode_member, run_direction, gauge_check)

# ---------------------------------------------------------------- defended constants (all from the prereg)
COLOR_SWAP = {"red": "blue", "blue": "red", "green": "yellow", "yellow": "green"}
SHAPE_SWAP = {"ball": "square", "square": "triangle", "triangle": "ball"}
COLOR_PHYSICS = {"red": 2.0, "blue": 0.5, "green": 1.4, "yellow": 0.9}          # world v2 (prereg F-leg)
V1_B_FWD = {"color": 0.351, "shape": 0.476, "motion": 0.465}                    # committed 316f648 baseline
PIXEL_VISION = ["vit_render", "clip_vision", "siglip_vision"]                   # prereg mechanism (i) members
ATTRS = ("color", "shape", "motion")
BAR_COLOR_ABS, BAR_COLOR_DELTA, BAR_COLLATERAL = 0.50, 0.15, 0.10               # prereg F-leg bars
ALL_NAMES = [m[0] for m in MEMBERS]

_PORTS = None


def _ports():
    """Lazy port loading: a fully cached rerun never touches the models."""
    global _PORTS
    if _PORTS is None:
        print("  [ports] loading frozen ports ...", flush=True)
        _PORTS = load_ports()
    return _PORTS


# ---------------------------------------------------------------- swapped worlds (D-leg instrument 2)
def _event_from_objs(objs):
    """Rebuild the full world event from a (post-processed) object list with the SAME world code
    (simulate/render/caption/dynamics_signature) — deterministic and index-matched to the original scene."""
    pos, vel = W.simulate(objs)
    mid = len(pos) // 2
    return {"render": W.render(objs, pos_frame=pos[mid]),
            "caption": W.caption(objs, vel_frame=vel[0]),
            "dynamics": W.dynamics_signature(pos, vel),
            "objs": objs}


def _swapped_events(seeds, field, mapping):
    """The SAME scenes under a global attribute permutation: swap the field on sample_scene's output, then
    re-simulate/render/caption with unchanged code."""
    evs = []
    for s in seeds:
        objs = W.sample_scene(s)
        for o in objs:
            o[field] = mapping[o[field]]
        evs.append(_event_from_objs(objs))
    return evs


# ---------------------------------------------------------------- primary-object attributes (D-leg labels)
def _motion_dir(obj):
    """left / right / still from the primary object's initial vx sign, |vx| > 1.2 (world.py's own threshold)."""
    if obj["vx"] > 1.2:
        return "right"
    if obj["vx"] < -1.2:
        return "left"
    return "still"


def _primary_attrs(scenes):
    return {"color": np.array([sc["objs"][0]["color"] for sc in scenes]),
            "shape": np.array([sc["objs"][0]["shape"] for sc in scenes]),
            "motion": np.array([_motion_dir(sc["objs"][0]) for sc in scenes])}


# ---------------------------------------------------------------- cached encoding (reuses v1 cache verbatim)
def encode_set(scenes, tag, members=MEMBERS):
    """Member-channel encodings of a scene list, cached per (tag, member). tag='' reuses overlap_routing's
    v1 cache files ({name}__L.npy) unchanged; other tags get their own variant files."""
    os.makedirs(CACHE, exist_ok=True)
    out = {}
    for name, _pn, _ch, _mod, _kind in members:
        fname = f"{name}__L.npy" if not tag else f"{tag}__{name}__L.npy"
        p = os.path.join(CACHE, fname)
        if os.path.exists(p):
            out[name] = np.load(p)
        else:
            print(f"  [encode] {tag or 'v1'}: {name} over {len(scenes)} scenes ...", flush=True)
            out[name] = _encode_member(name, _ports(), scenes)
            np.save(p, out[name])
    return out


# ---------------------------------------------------------------- D-leg instruments
def rho_table(Ds, attrs):
    """rho_attr per member: mean D over DIFFERENT-attr pairs / mean D over SAME-attr pairs (primary object)."""
    iu = np.triu_indices(N, 1)
    rho = {}
    for name in ALL_NAMES:
        d = Ds[name][iu]
        rho[name] = {}
        for at in ATTRS:
            lab = attrs[at]
            same = lab[iu[0]] == lab[iu[1]]
            rho[name][at] = float(d[~same].mean() / d[same].mean())
    return rho


def _rel_diff(D1, D0):
    return float(np.linalg.norm(D1 - D0) / np.linalg.norm(D0))


# ---------------------------------------------------------------- report helpers
def _fmt_acc(label, acc):
    return f"    {label:<22} color {acc['color']:.3f}   shape {acc['shape']:.3f}   motion {acc['motion']:.3f}"


def run():
    print("=" * 100)
    print("COLOR-SYMMETRY — diagnosis + fix cycle (executable of PREREG_color_symmetry.md @ 57b7afd)")
    print(f"  substrate N={N} (seeds 0..{N-1}); held-out K={K} (1000..{1000+K-1}); anchor m={M}; "
          f"solver seeds={SEEDS}; router = UNTOUCHED untied equilibrate (reused from overlap_routing)")
    print("=" * 100)

    # ============================================================ D-LEG (runs first; gates the F-leg)
    print("\n[D-leg] building v1 substrate + geometries (v1 encodings from overlap_routing's cache) ...",
          flush=True)
    sub_v1 = [W.event(s) for s in SUBSTRATE_SEEDS]
    Ls_v1 = encode_set(sub_v1, "")
    Ds_v1 = {name: cloud_to_Dw(Ls_v1[name])[0] for name in ALL_NAMES}
    attrs = _primary_attrs(sub_v1)

    rho = rho_table(Ds_v1, attrs)
    print("\n" + "=" * 100)
    print("D-LEG TABLE 1 — attribute-structure ratio rho  (mean D over DIFFERENT-attr pairs / SAME-attr "
          "pairs; ~1 = attribute does not structure the geometry)")
    print("=" * 100)
    print(f"    {'member-channel':<22} {'rho_color':>10} {'rho_shape':>10} {'rho_motion':>10}"
          f"   color<shape?")
    for name in ALL_NAMES:
        r = rho[name]
        mark = "  <-- pixel-vision (prereg (i))" if name in PIXEL_VISION else ""
        print(f"    {name:<22} {r['color']:>10.4f} {r['shape']:>10.4f} {r['motion']:>10.4f}"
              f"   {'yes' if r['color'] < r['shape'] else 'NO'}{mark}")

    print("\n[D-leg] regenerating the SAME 256 scenes under global color / shape permutations "
          "(deterministic, index-matched) ...", flush=True)
    Ls_cs = encode_set(_swapped_events(SUBSTRATE_SEEDS, "color", COLOR_SWAP), "colorswap")
    Ls_ss = encode_set(_swapped_events(SUBSTRATE_SEEDS, "shape", SHAPE_SWAP), "shapeswap")
    rd = {}
    for name in ALL_NAMES:
        rd[name] = {"color": _rel_diff(cloud_to_Dw(Ls_cs[name])[0], Ds_v1[name]),
                    "shape": _rel_diff(cloud_to_Dw(Ls_ss[name])[0], Ds_v1[name])}

    print("\n" + "=" * 100)
    print("D-LEG TABLE 2 — exchangeability (swap) test:  rel-diff = ||D_swap - D_orig||_F / ||D_orig||_F")
    print("  color perm: red<->blue, green<->yellow   |   shape perm: ball->square->triangle->ball")
    print("=" * 100)
    print(f"    {'member-channel':<22} {'colorswap':>12} {'shapeswap':>12}   color <= shape/2 ?")
    n_half = 0
    for name in ALL_NAMES:
        ok = rd[name]["color"] <= rd[name]["shape"] / 2.0
        n_half += int(ok)
        note = ""
        if name == "world_dynamics":
            note = "  <-- sanity row: colors (and shapes) have no v1 physics, expect ~0 / ~0"
        print(f"    {name:<22} {rd[name]['color']:>12.6f} {rd[name]['shape']:>12.6f}   "
              f"{'yes' if ok else 'NO'}{note}")

    # ------------------------------------------------------------ D-leg verdict (prereg gate, to the letter)
    mech_i = all(rho[name]["color"] < rho[name]["shape"] for name in PIXEL_VISION)
    mech_ii = n_half > len(ALL_NAMES) / 2.0
    confirmed = mech_i or mech_ii

    print("\n" + "=" * 100)
    print("D-LEG VERDICT (prereg gate)")
    print("=" * 100)
    print(f"  (i)  under-encoding : rho_color < rho_shape on ALL pixel-vision members "
          f"{PIXEL_VISION} : {'CONFIRMED' if mech_i else 'not confirmed'}")
    print(f"  (ii) exchangeability: rel-diff(colorswap) <= rel-diff(shapeswap)/2 on a majority of "
          f"member-channels : {n_half}/{len(ALL_NAMES)} : {'CONFIRMED' if mech_ii else 'not confirmed'}")
    if not confirmed:
        print("-" * 100)
        print("  D-LEG FAILS — diagnosis WRONG (honest branch): color is both well-encoded "
              "(rho_color >= rho_shape on pixel vision) AND non-exchangeable (swap rel-diffs comparable).")
        print("  The color failure has a deeper cause than the free-lunch orbit story. Per prereg the F-leg "
              "is NOT run on an unconfirmed diagnosis. STOP; re-derive before any fix attempt.")
        print("  OVERALL PREREG VERDICT BRANCH: diagnosis-wrong.")
        print("=" * 100)
        return {"rho": rho, "rel_diff": rd, "d_leg": {"mech_i": mech_i, "mech_ii": mech_ii,
                "confirmed": False}, "branch": "diagnosis-wrong"}
    which = [m for m, ok in (("(i) under-encoding", mech_i), ("(ii) exchangeability", mech_ii)) if ok]
    print("-" * 100)
    print(f"  D-LEG CONFIRMS via {' AND '.join(which)} — gate OPEN, running the registered F-leg.")
    print("=" * 100)

    # ============================================================ F-LEG (world v2: color covaries w/ speed)
    print(f"\n[F-leg] world v2 = same sampler + color_physics speed multipliers {COLOR_PHYSICS}")
    print("[F-leg] regenerating the FULL substrate + held-out queries under v2 (fresh renders AND captions "
          "AND dynamics for every condition-B member-channel) ...", flush=True)
    sub_v2 = [W.event(s, color_physics=COLOR_PHYSICS) for s in SUBSTRATE_SEEDS]
    qs_v2 = [W.event(s, color_physics=COLOR_PHYSICS) for s in QUERY_SEEDS]
    Ls_v2 = encode_set(sub_v2, "v2")
    qf_render = encode_set(qs_v2, "v2q", members=[m for m in MEMBERS if m[3] == "vision"])
    qf_caption = encode_set(qs_v2, "v2q", members=[m for m in MEMBERS if m[3] == "text"])
    Ds_v2 = {name: cloud_to_Dw(Ls_v2[name])[0] for name in ALL_NAMES}

    print(f"[F-leg] routing: condition B FORWARD render->text, {K} queries x {len(SEEDS)} seeds x "
          "read-members (untied equilibrate, verbatim overlap_routing machinery) ...", flush=True)
    res = run_direction("B", "fwd", Ds_v2, Ls_v2, qf_render, qf_caption, qs_v2, sub_v2)

    print("[F-leg] gauge check: scramble one silent member's features, re-equilibrate ...", flush=True)
    dF, F0, F1, victim = gauge_check(Ds_v2, Ls_v2, qf_render, qs_v2)

    acc, std = res["overall"], res["std"]
    print("\n" + "=" * 100)
    print("F-LEG ACCURACY TABLE — condition B FORWARD render->text (seed-averaged; chance floors "
          f"color {CHANCE['color']:.2f} / shape {CHANCE['shape']:.2f} / motion {CHANCE['motion']:.2f})")
    print("=" * 100)
    print(_fmt_acc("B (v1, committed)", V1_B_FWD) + "   (registered baseline, 316f648)")
    print(_fmt_acc("B (v2, this run)", acc) +
          f"   (std/seed  c{std['color']:.3f} s{std['shape']:.3f} m{std['motion']:.3f})")
    print(f"    {'delta v2 - v1':<22} color {acc['color']-V1_B_FWD['color']:+.3f}   "
          f"shape {acc['shape']-V1_B_FWD['shape']:+.3f}   motion {acc['motion']-V1_B_FWD['motion']:+.3f}")
    print(f"\n    gauge: scramble '{victim}' (silent):  F0={F0:.9f}  F1={F1:.9f}  |dF|={dF:.3e}")

    # ------------------------------------------------------------ registered bars (prereg, to the letter)
    b1 = acc["color"] >= BAR_COLOR_ABS and (acc["color"] - V1_B_FWD["color"]) >= BAR_COLOR_DELTA
    b2 = (acc["shape"] >= V1_B_FWD["shape"] - BAR_COLLATERAL and
          acc["motion"] >= V1_B_FWD["motion"] - BAR_COLLATERAL)
    b3 = dF < 1e-6
    f_pass = b1 and b2 and b3

    print("\n" + "=" * 100)
    print("F-LEG REGISTERED BARS")
    print("=" * 100)
    print(f"  (1) color recovers : B(v2) color >= {BAR_COLOR_ABS:.2f} AND B(v2)-{V1_B_FWD['color']:.3f} >= "
          f"{BAR_COLOR_DELTA:.2f} :  color={acc['color']:.3f}, delta={acc['color']-V1_B_FWD['color']:+.3f}"
          f"   {'PASS' if b1 else 'FAIL'}")
    print(f"  (2) no collateral collapse : shape >= {V1_B_FWD['shape']-BAR_COLLATERAL:.3f} AND motion >= "
          f"{V1_B_FWD['motion']-BAR_COLLATERAL:.3f} :  shape={acc['shape']:.3f}, motion={acc['motion']:.3f}"
          f"   {'PASS' if b2 else 'FAIL'}")
    print(f"  (3) gauge : |dF| < 1e-6 under scramble :  |dF|={dF:.3e}   {'PASS' if b3 else 'FAIL'}")
    print("-" * 100)
    branch = "empirically-pinned" if f_pass else "covariance-insufficient"
    if f_pass:
        print("  OVERALL PREREG VERDICT BRANCH: empirically-pinned — D-leg confirmed AND F-leg passed.")
        print("  The free-lunch orbit story is EMPIRICALLY PINNED: what routes untied is what breaks")
        print("  exchangeability; the dictionary is needed precisely for orbit-internal attributes.")
        print("  (This is the quantitative version of the wall, not its removal.)")
    else:
        print("  OVERALL PREREG VERDICT BRANCH: covariance-insufficient — D-leg confirmed but the F-leg")
        print("  FAILED its registered bars: symmetry-breaking covariance is insufficient; deeper wall.")
        print("  Reported straight; no substrate retuning, no post-hoc tweak.")
    print("-" * 100)
    print("  HONEST CONFOUND (registered): in world v2 a text member can reach color VIA motion words alone")
    print("  (red<->fast). v2 color recovery therefore proves that SYMMETRY-BREAKING COVARIANCE routes —")
    print("  it does NOT prove that pixel-color routes. The router itself was untouched throughout; only")
    print("  the measurement (D-leg) and the world's data distribution (F-leg) changed.")
    print("=" * 100)

    return {"rho": rho, "rel_diff": rd,
            "d_leg": {"mech_i": mech_i, "mech_ii": mech_ii, "confirmed": True},
            "f_leg": {"acc": acc, "std": std, "dF": dF,
                      "bars": {"b1": bool(b1), "b2": bool(b2), "b3": bool(b3), "pass": bool(f_pass)}},
            "branch": branch}


if __name__ == "__main__":
    run()
